// ─── Utility: Generate realistic price history ────────────────────────────
export function genHistory(high, low, current, months = 12) {
  const labels = [];
  const data = [];
  let price = Math.round((high + low) / 2);
  const now = new Date();
  for (let i = months - 1; i >= 0; i--) {
    const d = new Date(now.getFullYear(), now.getMonth() - i, 1);
    labels.push(d.toLocaleDateString("en-IN", { month: "short", year: "2-digit" }));
    const delta = (Math.random() - 0.48) * (high - low) * 0.25;
    price = Math.round(Math.min(high, Math.max(low, price + delta)));
    data.push(price);
  }
  data[data.length - 1] = current;
  return { labels, data };
}

